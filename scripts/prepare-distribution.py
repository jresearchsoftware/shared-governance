# Exact ordinary AGENTS contribution emitted by the pinned VibeVM 1.0.7 probe.
BOOT_BLOCK = '''<vibevm>
<!-- Generated by vibe — do not edit inside this block; it is rewritten on `vibe install`. Text outside the <vibevm> markers is yours. -->

# Session boot

This project's boot sequence is computed by vibe (the PROP-009 loading
model). To begin a session, read these files in order:

1. `vibevm/vibespecs/boot/STATIC.md` — if it exists. The static (priority) lane: read it
   first and in full.
2. `vibevm/vibespecs/boot/INDEX.md` — a generated TOML manifest. Read every file named
   by its `[[entry]]` tables, in the listed order. A `kind = "static"`
   entry is read directly; a `kind = "dynamic"` entry is an INCLUDE
   resolved at boot, and one carrying a `when` condition is read only when
   that condition holds for the current session.

Boot is pure file-reading — there is nothing to execute.
</vibevm>'''


def vibe_hash(files):
    """Pinned VibeVM 1.0.7 legacy tree recipe, for this bounded UTF-8 file set."""
    digest = hashlib.sha256()
    for name in sorted(files, key=lambda name: Path(name).parts):
        digest.update(name.encode() + b"\0" + files[name] + b"\0")
    return "sha256:" + digest.hexdigest()


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT)


def validate_skill_links(files, prefix):
    """Keep passive Markdown references within the selected export (also legacy Skills)."""
    for name, data in files.items():
        if not name.startswith(prefix + "/"):
            continue
        prose = re.sub(r"^```[^\n]*\n.*?^```\s*$", "", data.decode(), flags=re.M | re.S)
        targets = re.findall(r"\[[^\]\n]*\]\(\s*(<[^>\n]*>|[^)\s]+)", prose)
        targets += re.findall(r"^ {0,3}\[[^\]\n]+\]:\s*(<[^>\n]*>|[^\s]+)", prose, flags=re.M)
        for target in targets:
            url = urlsplit(target.strip("<>"))
            if url.scheme or url.netloc:
                continue
            resolved = posixpath.normpath(posixpath.join(posixpath.dirname(name), unquote(url.path))) if url.path else name
            if not resolved.startswith(prefix + "/") or resolved not in files:
                raise ValueError("passive payload has an escaping or missing local reference: " + name)


def slot(version):
    return "vibevm/vibedeps/org.jresearch.ai.development-governance/" + version


def validate_rule_addresses(files):
    """Bounded Markdown checks, not a rule registry or semantic attestation."""
    prefixes = {PROTOCOL: "PC", AUTHORITY: "RA", VERSIONING: "PV", HANDOFF: "TH",
                SELF_ADOPTION: "SA", REPOSITORY_GOVERNANCE: "GH", INDEPENDENT_REVIEW: "IR",
                CONTRACT_MAINTENANCE: "CD", CONTEXT_LOADING: "CL"}
    addresses, documents = {}, {}
    for name, data in files.items():
        if not name.endswith(".md"):
            continue
        prose = re.sub(r"^```[^\n]*\n.*?^```\s*$", "", data.decode(), flags=re.M | re.S)
        labels = re.findall(r'<a id="([A-Z]+-[0-9]{3})"></a>', prose)
        for label in labels:
            if label in addresses:
                raise ValueError("duplicate stable rule address: " + label)
            addresses[label] = name
        if name in prefixes and (not labels or any(not label.startswith(prefixes[name] + "-") for label in labels)):
            raise ValueError("canonical protocol rule addresses missing or misprefixed: " + name)
        documents[name] = prose
    for name, prose in documents.items():
        for target in re.findall(r"\[[^\]\n]*\]\(\s*(<[^>\n]*>|[^)\s]+)", prose):
            url = urlsplit(target.strip("<>"))
            if url.scheme or url.netloc or not re.fullmatch(r"[A-Z]+-[0-9]{3}", unquote(url.fragment)):
                continue
            resolved = posixpath.normpath(posixpath.join(posixpath.dirname(name), unquote(url.path))) if url.path else name
            if addresses.get(unquote(url.fragment)) != resolved:
                raise ValueError("missing or redirected stable rule reference: " + name + " -> " + target)


def package_path(revision):
    members = tomllib.loads(git("show", revision + ":vibe.toml").decode())["workspace"]["members"]
    if members not in ([PACKAGE], [HISTORICAL_PACKAGE]):
        raise ValueError("source has no supported single package authoring path")
    return members[0]


def validate_payload(files, license_bytes, historical=False):
    """Bound this repository's passive flow; historical exports retain their old shape."""
    for data in files.values():
        data.decode("utf-8")
    if "vibe.toml" not in files or "LICENSE" not in files:
        raise ValueError("source commit has no complete package")
    manifest = tomllib.loads(files["vibe.toml"].decode())
    package = manifest.get("package", {})
    if not isinstance(package, dict):
        raise ValueError("source package metadata must be a table")
    expected = {"group": "org.jresearch.ai", "name": "development-governance",
                "kind": "flow", "format": "simple", "epoch": 1,
                "publish": False, "frozen": True, "license": "MIT"}
    if any(type(package.get(key)) is not type(value) or package.get(key) != value
           for key, value in expected.items()):
        raise ValueError("source package identity/passivity/publication boundary differs")
    if set(manifest) != {"package", "boot_snippet"}:
        raise ValueError("unexpected package capability or dependency")
    version = package.get("version")
    if not isinstance(version, str) or not re.fullmatch(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", version):
        raise ValueError("package must have a release SemVer version")
    if historical and version != "0.1.0":
        raise ValueError("historical frozen package version differs")
    if set(package) - (set(expected) | {"description", "version"}):
        raise ValueError("unexpected package metadata")
    boot = {"source": "vibevm/vibespecs/boot/development-governance.md",
            "category": "flow", "link": "dynamic"}
    if manifest["boot_snippet"] != boot:
        raise ValueError("package boot declaration differs")
    allowed = {"vibe.toml", "LICENSE", "README.md", boot["source"], PROTOCOL}
    if not historical:
        allowed.add(VERSIONING)
    # Earlier full-commit exports retain their accepted one/two/three-protocol shapes.
    if tuple(map(int, version.split("."))) >= (1, 1, 0):
        allowed.add(AUTHORITY)
    if tuple(map(int, version.split("."))) >= (1, 2, 0):
        allowed.add(HANDOFF)
    if tuple(map(int, version.split("."))) >= (1, 3, 0):
        allowed.add(SELF_ADOPTION)
    if tuple(map(int, version.split("."))) >= (2, 1, 0):
        allowed.add(REPOSITORY_GOVERNANCE)
    if tuple(map(int, version.split("."))) >= (2, 2, 0):
        allowed.add(INDEPENDENT_REVIEW)
    if tuple(map(int, version.split("."))) >= (2, 3, 0):
        # Optional manually invoked maintenance assets, never boot/executable capabilities.
        allowed.update({"tools/chatgpt/project.py", "tools/chatgpt/base.md", "tools/chatgpt/README.md"})
    if tuple(map(int, version.split("."))) >= (2, 4, 0):
        allowed.add(CONTRACT_MAINTENANCE)
    if tuple(map(int, version.split("."))) >= (2, 5, 0):
        allowed.add(CONTEXT_LOADING)
    if tuple(map(int, version.split("."))) >= (2, 6, 0):
        allowed.update({ONBOARDING, ONBOARDING_EXAMPLES})
    if tuple(map(int, version.split("."))) >= (2, 7, 0):
        allowed.add(ENGINEERING_METHODS)
    if tuple(map(int, version.split("."))) >= (3, 0, 0):
        allowed.add(CHANGELOG)
    if set(files) != allowed:
        raise ValueError("source package file set differs from declared passive payload")
    if files["LICENSE"] != license_bytes:
        raise ValueError("source/package license notices differ")
    validate_skill_links(files, "vibevm/vibespecs")
    protocols = allowed & {PROTOCOL, VERSIONING, AUTHORITY, HANDOFF, SELF_ADOPTION,
                           REPOSITORY_GOVERNANCE, INDEPENDENT_REVIEW, CONTRACT_MAINTENANCE,
                           CONTEXT_LOADING}
    if any(not files[name].strip() for name in protocols):
        raise ValueError("canonical protocol is empty")
    if any(not files[name].strip() for name in allowed & {ONBOARDING, ONBOARDING_EXAMPLES,
                                                       ENGINEERING_METHODS}):
        raise ValueError("operator guide is empty")
    if CHANGELOG in allowed:
        if not files[CHANGELOG].strip():
            raise ValueError("installed changelog is empty")
        validate_rule_addresses(files)
    return manifest


def snapshot(revision):
    # Full commits make preparation stable even when source branches/tags move.
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("--source-ref must be a full 40-character source commit SHA")
    resolved = git("rev-parse", "--verify", revision + "^{commit}").decode().strip()
    if resolved != revision:
        raise ValueError("source commit identity differs")
    package_root = package_path(revision)
    files = {}
    for entry in git("ls-tree", "-rz", revision, "--", package_root).split(b"\0"):
        if not entry:
            continue
        metadata, name = entry.split(b"\t", 1)
        mode, kind, oid = metadata.decode().split()
        relative = Path(name.decode()).relative_to(package_root).as_posix()
        if relative in SOURCE_ARTIFACTS:
            continue
        if mode != "100644" or kind != "blob":
            raise ValueError("package contains a non-ordinary file: " + relative)
        files[relative] = git("cat-file", "blob", oid)
    manifest = validate_payload(files, git("show", revision + ":LICENSE"), package_root == HISTORICAL_PACKAGE)
    hashes = {name: hashlib.sha256(data).hexdigest() for name, data in sorted(files.items())}
    # Hash the sorted path/hash map, binding both file names and file bytes.
    content = hashlib.sha256(json.dumps(hashes, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    receipt = {"schema": 1, "source_repository": REPOSITORY, "source_revision": revision,
               "source_path": package_root, "package": COORDINATE, "version": manifest["package"]["version"],
               "payload_sha256": content, "sha256": hashes}
    files[RECEIPT] = (json.dumps(receipt, indent=2, sort_keys=True) + "\n").encode()
    return files, receipt


def prepare(revision, destination):
    files, receipt = snapshot(revision)  # Validate before creating any output.
    destination = Path(destination)
    if destination.is_symlink() or destination.resolve().is_relative_to(ROOT):
        raise ValueError("distribution destination must be outside the authoring checkout, not a symlink")
    if destination.exists() and (not destination.is_dir() or any(destination.iterdir())):
        raise ValueError("destination must be absent or empty; distribution is not overwritten")
    destination.mkdir(parents=True, exist_ok=True)
    for relative, data in files.items():
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    return receipt


def verify(revision, directory, installed=False, native=False):
    # Rebuild expectations from canonical Git, never trust a co-located receipt alone.
    files, receipt = snapshot(revision)
    if native:
        files.pop(RECEIPT)
    directory = Path(directory)
    if directory.is_symlink() or not directory.is_dir():
        raise ValueError("distribution must be an ordinary directory")
    actual = set()
    for path in directory.rglob("*"):
        relative = path.relative_to(directory).as_posix()
        if relative == ".git" or relative.startswith(".git/"):
            continue
        if path.is_symlink():
            raise ValueError("distribution contains a symlink: " + relative)
        if path.is_file():
            actual.add(relative)
        elif not path.is_dir():
            raise ValueError("distribution contains a non-ordinary file: " + relative)
    if installed:
        actual.discard(".vibe-slot.toml")
        marker = tomllib.loads((directory / ".vibe-slot.toml").read_text())
        entries = [{"path": name, "sha256": hashlib.sha256(data).hexdigest()}
                   for name, data in sorted(files.items())]
        if (set(marker) != {"schema", "source_hash", "spec_format", "file"}
                or marker["schema"] != 1 or marker["spec_format"] != "mixed"
                or marker["source_hash"] != vibe_hash(files) or marker["file"] != entries):
            raise ValueError("installed slot metadata differs from canonical source identity")
    if actual != set(files):
        raise ValueError("distribution file set differs; missing=" + repr(sorted(set(files) - actual))
                         + "; extra=" + repr(sorted(actual - set(files))))
    for relative, expected in files.items():
        if (directory / relative).read_bytes() != expected:
            raise ValueError("distribution bytes differ: " + relative)
    return receipt


def stage_producer(revision, directory=ROOT):
    """Reuse exact Git export for the ordinary versioned in-tree registry.

    Local source + projection inherit the owning accepted Git commit's provenance;
    the release-only DISTRIBUTION receipt would create a self-referential commit pin.
    No resolution, installation or authority selection. Regeneration updates only
    this version's known generated payload; unexpected content is preserved/rejected.
    """
    files, receipt = snapshot(revision)
    files.pop(RECEIPT)
    target = Path(directory) / "vibevm/vibepacks" / COORDINATE / ("v" + receipt["version"])
    if target == Path(directory) / HISTORICAL_PACKAGE:
        raise ValueError("the historical frozen authoring root cannot be regenerated")
    if target.is_symlink() or not target.resolve().is_relative_to(Path(directory).resolve()):
        raise ValueError("native source must stay inside the producer")
    if target.exists():
        for path in target.rglob("*"):
            if path.is_symlink() or (path.is_file() and path.relative_to(target).as_posix() not in files):
                raise ValueError("native source contains unexpected content; preserve it for diagnosis")
    target.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_bytes() != data:
            path.write_bytes(data)
    return receipt


def verify_producer(revision, directory=ROOT):
    """Bind authored source, registry, slots, lock and native routes to exact Git.

    Native source_url/timestamp are location metadata; content identity is canonical.
    Existing exporter comparisons detect the pinned tool's stale-source/slot gaps.
    """
    directory = Path(directory)
    files, receipt = snapshot(revision)
    files.pop(RECEIPT)
    version = receipt["version"]
    authored = {}
    for path in (directory / PACKAGE).rglob("*"):
        relative = path.relative_to(directory / PACKAGE).as_posix()
        if path.is_symlink():
            raise ValueError("producer authored source contains a symlink")
        if path.is_file() and relative not in SOURCE_ARTIFACTS and relative != "vibevm/vibespecs/boot/.vibe-boot-artifacts.lock":
            authored[relative] = path.read_bytes()
    if authored != files:
        raise ValueError("producer authored bytes differ from the selected Git export")
    source = directory / "vibevm/vibepacks" / COORDINATE / ("v" + version)
    verify(revision, source, native=True)
    manifest = tomllib.loads((directory / "vibe.toml").read_text(encoding="utf-8"))
    requirement = manifest.get("requires", {}).get("packages", {})
    relay = "flow:org.jresearch.ai/codex-relay" in requirement
    if relay:
        spec = importlib.util.spec_from_file_location("relay_skill", ROOT / "scripts/relay-skill.py")
        integration = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(integration)
        integration.check(directory, files, vibe_hash)
    else:
        verify(revision, directory / slot(version), installed=True, native=True)
    if not relay and requirement != {"flow:" + COORDINATE: {"version": "=" + version, "link": "dynamic"}}:
        raise ValueError("producer must declare one exact-version dynamic flow")
    lock = tomllib.loads((directory / "vibe.lock").read_text(encoding="utf-8"))
    if not relay and (lock.get("meta", {}).get("schema_version") != 7 or lock["meta"].get("root_dependencies") != ["flow:" + COORDINATE + "@=" + version]):
        raise ValueError("producer lock root identity differs")
    entries = lock.get("package", [])
    if not relay and (len(entries) != 1 or any(entries[0].get(key) != value for key, value in {
            "kind": "flow", "group": "org.jresearch.ai", "name": "development-governance",
            "version": version, "content_hash": vibe_hash(files), "source_kind": "registry"}.items())):
        raise ValueError("producer lock differs from exact authored content")
    url = entries[0].get("source_url", "")
    if not relay and (not url.startswith("file://") or not url.endswith("/vibevm/vibepacks/" + COORDINATE + "/v" + version)):
        raise ValueError("producer lock source is not a generated in-tree registry URL")
    roots = (directory, directory / PACKAGE)
    expected = ([{"path": "vibevm/vibespecs/boot/00-authoring.md", "kind": "static"},
                 {"path": slot(version) + "/vibevm/vibespecs/boot/development-governance.md", "kind": "static"}],
                [{"path": PACKAGE + "/vibevm/vibespecs/boot/development-governance.md", "kind": "static"}])
    if relay:
        expected[0].append({"path": integration.SLOT + "/vibevm/vibespecs/boot/codex-relay.md", "kind": "static"})
    for root, routes in zip(roots, expected):
        index = root / BOOT_INDEX
        if index.is_symlink() or not index.is_file():
            raise ValueError("producer native index is missing")
        boot = tomllib.loads(index.read_text(encoding="utf-8"))
        if boot.get("schema") != 1 or boot.get("entry") != routes or (root / "vibevm/vibespecs/boot/STATIC.md").exists():
            raise ValueError("producer native boot routes differ")
        for name in ("AGENTS.md", "CLAUDE.md", "GEMINI.md"):
            route = root / name
            if route.is_symlink() or not route.is_file():
                raise ValueError("producer agent route is missing: " + name)
            text = route.read_text(encoding="utf-8")
            if re.findall(r"<vibevm>.*?</vibevm>", text, flags=re.S) != [BOOT_BLOCK]:
                raise ValueError("producer generated agent route differs: " + name)
            if root != directory and text.strip() != BOOT_BLOCK:
                raise ValueError("package member route contains an unexpected local overlay")
    # This producer explicitly selects review methodology; other consumers do not.
    agents = (directory / "AGENTS.md").read_text(encoding="utf-8")
    if "scripts/self-adopt.py" in agents or any(Path(topic).name not in agents for topic in
            (PROTOCOL, AUTHORITY, VERSIONING, HANDOFF, SELF_ADOPTION, INDEPENDENT_REVIEW)):
        raise ValueError("producer conditional adoption/retired helper route differs")
    return receipt


def verify_consumer(revision, directory):
    directory = Path(directory)
    files, receipt = snapshot(revision)
    version = receipt["version"]
    slot_path = slot(version)
    verify(revision, directory / slot_path, installed=True)
    manifest = tomllib.loads((directory / "vibe.toml").read_text())
    requires = manifest.get("requires", {})
    packages = requires.get("packages", {}) if isinstance(requires, dict) else None
    requirement = packages.get(COORDINATE) if isinstance(packages, dict) else None
    if (not isinstance(requirement, dict) or requirement.get("version") != "=" + version
            or not isinstance(requirement.get("git"), str) or not requirement["git"]
            or bool(requirement.get("tag")) == bool(requirement.get("rev"))
            or requirement.get("branch")):
        raise ValueError("consumer must declare exact-version Git tag/rev requirement")
    if (requirement.get("rev") and (not isinstance(requirement["rev"], str)
                                   or not re.fullmatch(r"[0-9a-f]{40}", requirement["rev"]))):
        raise ValueError("consumer Git revision must be a full commit SHA")
    lock = tomllib.loads((directory / "vibe.lock").read_text())
    meta = lock.get("meta")
    if not isinstance(meta, dict) or type(meta.get("schema_version")) is not int or meta["schema_version"] != 7:
        raise ValueError("consumer lock must use pinned VibeVM schema 7")
    locked = lock.get("package", [])
    if not isinstance(locked, list) or any(not isinstance(entry, dict) for entry in locked):
        raise ValueError("consumer lock packages must be tables")
    packages = [entry for entry in locked if
                entry.get("group") == "org.jresearch.ai" and entry.get("name") == "development-governance"]
    if len(packages) != 1:
        raise ValueError("consumer lock has no unique package identity")
    entry = packages[0]
    if any(entry.get(key) != value for key, value in {
            "version": version, "source_kind": "git", "source_url": requirement["git"],
            "source_ref": requirement.get("rev") or requirement["tag"], "content_hash": vibe_hash(files)}.items()):
        raise ValueError("consumer lock differs from canonical content/source declaration")
    # The removed package Skill and its native receipt must not remain active.
    for relative in (".agents/skills/proportional-controls",
                     ".agents/skills/.proportional-controls.vibe-skill-receipt.toml"):
        if (directory / relative).exists() or (directory / relative).is_symlink():
            raise ValueError("consumer retains the removed native Skill: " + relative)
    index = directory / BOOT_INDEX
    agents = directory / "AGENTS.md"
    if any(path.is_symlink() or not path.is_file() for path in (index, agents)):
        raise ValueError("consumer generated boot route must use ordinary files")
    boot = tomllib.loads(index.read_text(encoding="utf-8"))
    package_boot = slot_path + "/vibevm/vibespecs/boot/development-governance.md"
    entries = boot.get("entry", [])
    if (type(boot.get("schema")) is not int or boot["schema"] != 1 or not isinstance(entries, list)
            or any(not isinstance(e, dict) or not isinstance(e.get("path"), str) for e in entries)):
        raise ValueError("consumer boot index differs from pinned schema")
    selected = [e for e in entries if posixpath.normpath(e["path"]).startswith(slot_path + "/")]
    # Pinned upstream emits static despite the authored link=dynamic. Qualify it honestly.
    if selected != [{"path": package_boot, "kind": "static"}]:
        raise ValueError("consumer boot index has no unique canonical package route")
    blocks = re.findall(r"<vibevm>.*?</vibevm>", agents.read_text(encoding="utf-8"), flags=re.S)
    if blocks != [BOOT_BLOCK]:
        raise ValueError("consumer AGENTS does not route through the generated boot index")
    return receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-ref", required=True, help="full source commit; acceptance is verified by its owner")
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--destination", type=Path, help="new/empty directory outside this authoring checkout")
    action.add_argument("--verify", type=Path, metavar="DIRECTORY", help="compare prepared bytes with canonical source")
    action.add_argument("--verify-installed", type=Path, metavar="DIRECTORY", help="also validate VibeVM's generated slot receipt")
    action.add_argument("--verify-consumer", type=Path, metavar="DIRECTORY", help="validate manifest, lock, installed bytes and absence of the removed native Skill")
    action.add_argument("--producer-source", action="store_true", help="stage the exact export in this producer's versioned local registry")
    action.add_argument("--verify-producer", action="store_true", help="compare committed native producer state with exact source")
    args = parser.parse_args()
    try:
        if args.producer_source:
            receipt = stage_producer(args.source_ref)
        elif args.verify_producer:
            receipt = verify_producer(args.source_ref)
        elif args.destination is not None:
            receipt = prepare(args.source_ref, args.destination)
        elif args.verify_consumer:
            receipt = verify_consumer(args.source_ref, args.verify_consumer)
        else:
            receipt = verify(args.source_ref, args.verify or args.verify_installed, bool(args.verify_installed))
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        parser.exit(1, "Distribution validation failed: " + str(error) + "\n")
    action_name = "stage-native-source" if args.producer_source else "prepare" if args.destination else "verify"
    print(json.dumps({"distribution": "PASS", "action": action_name,
                      "source_revision": receipt["source_revision"],
                      "payload_sha256": receipt["payload_sha256"], "files": len(receipt["sha256"]),
                      "publication": "this command never publishes; acceptance/remote authority are external"}))


